package com.nextstep.app.domain.year

/**
 * 올해 할 일의 층.
 * - [BASE] 기본: 그 나이에 이만큼이면 충분한 것. 진행률은 기본만 셉니다.
 * - [AHEAD] 앞서 가기: 기본을 채우고 여유가 있을 때, 미리 해 두면 다음 해의 고비를 쉽게 넘는 것.
 *   빨리 나가는 선행보다 깊게(심화) · 넓게(독서·어휘·배경지식) · 스스로 하는 도구(계획·오답·요약)를 먼저 두고,
 *   다음 해 내용은 학년 말(겨울방학)에 개념만 가볍게 봅니다. 학령 전에는 공부가 아니라 놀이·대화를 넓히는 것만 둡니다.
 *   못 해도 밀림·알림이 없습니다.
 */
enum class YearTier(val label: String) {
    BASE("기본"),
    AHEAD("앞서 가기"),
}
